return function(T)
    local N=require('bookfetch.names')
    T.test('vfat characters and controls',function() T.eq(N.clean('  A/B\\C:*?"<>|\0\1\127  '),'ABC') end)
    T.test('whitespace and dots',function() T.eq(N.clean(' . a\n\t b . '),'a b') end)
    T.test('empty and reserved names',function() T.eq(N.clean('...'),'Untitled'); T.eq(N.clean('CON'),'_CON') end)
    T.test('two-byte UTF-8 boundary',function() T.eq(N.truncate('ééé',5),'éé') end)
    T.test('three-byte UTF-8 boundary',function() T.eq(N.truncate('水水',5),'水') end)
    T.test('four-byte UTF-8 boundary',function() T.eq(N.truncate('📖📖',7),'📖') end)
    T.test('invalid UTF-8 tail',function() T.eq(N.truncate('abc\240\128',120),'abc') end)
    T.test('filename includes extension in 120-byte limit',function()
        local filename=N.filename({title=string.rep('📖',60),author='Ada',format='epub'},2)
        T.truth(#filename<=120); T.eq(filename:sub(-9),' (2).epub')
    end)
    T.test('filename collisions',function()
        local b={title='Title',author='Author',format='pdf'}
        T.eq(N.available('/Books',b,function(p) return p=='/Books/Title - Author.pdf' end),'/Books/Title - Author (2).pdf')
    end)
    T.test('extension path traversal refused',function() T.eq(pcall(N.filename,{title='T',format='../pdf'}),false) end)
end
