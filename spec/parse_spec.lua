return function(T)
    local P=require('bookfetch.parse')
    T.test('entities including Unicode',function() T.eq(P.entities('&amp; &quot; &#233; &#x1f4d6; &unknown;'),'& " é 📖 &unknown;') end)
    T.test('attribute quote styles',function() T.eq(P.attribute("href='a&amp;b' class=\"x\"",'href'),'a&b') end)
    T.test('realistic search cards scoped and deduplicated',function()
        local books=P.search(T.fixture('search.html'))
        T.eq(#books,3); T.eq(books[1].title,'The & Book 📖'); T.eq(books[1].author,'Ada Lovelace')
        T.eq(books[1].format,'epub'); T.eq(books[1].language,'en'); T.eq(books[1].year,'2019'); T.eq(books[1].size,'1.2MB')
        T.eq(books[2].md5,'fedcba9876543210fedcba9876543210'); T.eq(books[2].author,''); T.eq(books[2].format,nil)
        T.eq(books[3].title,'Études – été'); T.eq(books[3].author,'François'); T.eq(books[3].format,'pdf')
    end)
    T.test('LibGen GET link decoding',function() T.eq(P.libgen(T.fixture('libgen.html')),'get.php?md5=0123456789abcdef0123456789abcdef&key=PARTNERKEY') end)
    T.test('LibGen search rows',function()
        local books=P.libgen_search(T.fixture('libgen_search.html'))
        T.eq(#books,3); T.eq(books[1].md5,'0f70e5f5dcf80b046fa7f00b99fab2fe')
        T.eq(books[1].title,'In pursuit of Treasure island'); T.eq(books[1].author,'Raul Ruiz')
        T.eq(books[1].publisher,'Dis Voir'); T.eq(books[1].year,'2008'); T.eq(books[1].language,'English')
        T.eq(books[1].size,'2 MB'); T.eq(books[1].format,'pdf')
        T.eq(P.libgen_search('<table><tr><td>no md5 here</td></tr></table>')[1],nil)
    end)
    T.test('LibGen MD5 binding',function() T.eq(P.libgen(T.fixture('libgen.html'),string.rep('f',32)),nil) end)
    T.test('DDoS-Guard redirect cookie and HTML',function()
        T.truth(P.blocked(302,{location='/search?check=1'},'')); T.eq(P.blocked(200,{['set-cookie']='__ddg1=foo'},''),false); T.truth(P.blocked(403,{},''))
        T.truth(P.blocked(200,{},'<title>DDoS-Guard</title>')); T.eq(P.blocked(200,{},'ok'),false)
    end)
    T.test('metadata never inherits format or year from title',function()
        local books=P.search(T.fixture('metadata.html'))
        T.eq(books[1].title,'Mastering PDF'); T.eq(books[1].format,'epub'); T.eq(books[1].year,'2020')
        T.eq(books[2].title,'1984'); T.eq(books[2].year,nil); T.eq(books[2].format,nil)
    end)
    T.test('title classes and publisher years never become metadata',function()
        local books=P.search('<div><a class="text-sm" href="/md5/'..string.rep('a',32)..'">1984 Mastering PDF</a>'
            ..'<div class="publisher text-xs">Press 2024</div></div>')
        T.eq(books[1].format,nil); T.eq(books[1].year,nil)
        books=P.search('<div><a href="/md5/'..string.rep('b',32)..'">1984 Mastering PDF</a>'
            ..'<div data-format="epub" data-year="2023" data-language="en" data-size="2 MB"></div></div>')
        T.eq(books[1].format,'epub'); T.eq(books[1].year,'2023'); T.eq(books[1].language,'en'); T.eq(books[1].size,'2 MB')
    end)
    T.test('author ancestor walk is bounded',function()
        local html='<div><a>Outside'..string.rep('<div>',20)
            ..'<span class="mdi--user-edit"></span>'..string.rep('</div>',20)..'</a>'
            ..'<a href="/md5/'..string.rep('a',32)..'">Title</a></div>'
        local books=P.search(html); T.eq(#books,1); T.truth(books[1].title=='Title'); T.eq(books[1].author,'')
    end)
    T.test('unknown format sniffing rejects ambiguous content',function()
        T.eq(P.sniff('%PDF-1.7'),'pdf'); T.eq(P.sniff('PK\3\4mimetypeapplication/epub+zip'),'epub')
        T.eq(P.sniff('PK\3\4unknown'),nil)
        T.eq(P.sniff('<html>bad</html>'),nil)
    end)
    for _,format in ipairs({'epub','cbz','docx'}) do T.test('ZIP signature '..format,function() T.truth(P.magic('PK\3\4xx',format)) end) end
    T.test('PDF signature',function() T.truth(P.magic('%PDF-1.7','pdf')) end)
    for _,format in ipairs({'mobi','azw','azw3'}) do T.test('MOBI offset '..format,function() T.truth(P.magic(string.rep('\0',60)..'BOOKMOBI',format)) end) end
    T.test('DJVU signature',function() T.truth(P.magic('AT&TFORMxx','djvu')) end)
    T.test('FB2 XML signature',function() T.truth(P.magic('\239\187\191 <?xml version="1.0"?><FictionBook/>','fb2')) end)
    T.test('text signature',function() T.truth(P.magic('Plain text','txt')); T.eq(P.magic('a\0b','txt'),nil) end)
    T.test('reject HTML by bytes and MIME',function()
        T.eq(P.magic(' \n<!DOCTYPE html>bad','txt'),nil); T.eq(P.magic('%PDF','pdf','text/html'),nil)
        T.eq(P.magic('<html>bad','epub'),nil); T.eq(P.magic('PK\3\4','pdf'),nil)
    end)
end
