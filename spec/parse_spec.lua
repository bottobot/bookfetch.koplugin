return function(T)
    local P=require('bookfetch.parse')
    T.test('entities including Unicode',function() T.eq(P.entities('&amp; &quot; &#233; &#x1f4d6; &unknown;'),'& " é 📖 &unknown;') end)
    T.test('attribute quote styles',function() T.eq(P.attribute("href='a&amp;b' class=\"x\"",'href'),'a&b') end)
    T.test('realistic search cards scoped and deduplicated',function()
        local books=P.search(T.fixture('search.html'))
        T.eq(#books,3); T.eq(books[1].title,'The & Book 📖'); T.eq(books[1].author,'Ada Lovelace')
        T.eq(books[1].format,'epub'); T.eq(books[1].language,'en'); T.eq(books[1].year,'2019'); T.eq(books[1].size,'1.2MB')
        T.eq(books[2].md5,'fedcba9876543210fedcba9876543210'); T.eq(books[2].author,''); T.eq(books[2].format,nil)
        T.eq(books[3].title,'Études – été'); T.eq(books[3].author,'François'); T.eq(books[3].format,'pdf')
    end)
    T.test('LibGen GET link decoding',function() T.eq(P.libgen(T.fixture('libgen.html')),'get.php?md5=0123456789abcdef0123456789abcdef&key=PARTNERKEY') end)
    T.test('LibGen MD5 binding',function() T.eq(P.libgen(T.fixture('libgen.html'),string.rep('f',32)),nil) end)
    T.test('DDoS-Guard redirect cookie and HTML',function()
        T.truth(P.blocked(302,{location='/search?check=1'},'')); T.truth(P.blocked(200,{['set-cookie']='__ddg1=foo'},''))
        T.truth(P.blocked(200,{},'<title>DDoS-Guard</title>')); T.eq(P.blocked(200,{},'ok'),false)
    end)
    for _,format in ipairs({'epub','cbz','docx'}) do T.test('ZIP signature '..format,function() T.truth(P.magic('PK\3\4xx',format)) end) end
    T.test('PDF signature',function() T.truth(P.magic('%PDF-1.7','pdf')) end)
    for _,format in ipairs({'mobi','azw','azw3'}) do T.test('MOBI offset '..format,function() T.truth(P.magic(string.rep('\0',60)..'BOOKMOBI',format)) end) end
    T.test('DJVU signature',function() T.truth(P.magic('AT&TFORMxx','djvu')) end)
    T.test('FB2 XML signature',function() T.truth(P.magic('\239\187\191 <?xml version="1.0"?><FictionBook/>','fb2')) end)
    T.test('text signature',function() T.truth(P.magic('Plain text','txt')); T.eq(P.magic('a\0b','txt'),nil) end)
    T.test('reject HTML by bytes and MIME',function()
        T.eq(P.magic(' \n<!DOCTYPE html>bad','txt'),nil); T.eq(P.magic('%PDF','pdf','text/html'),nil)
        T.eq(P.magic('<html>bad','epub'),nil); T.eq(P.magic('PK\3\4','pdf'),nil)
    end)
end
